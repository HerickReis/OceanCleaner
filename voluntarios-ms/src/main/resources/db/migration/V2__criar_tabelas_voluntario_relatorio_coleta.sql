CREATE TABLE TB_VOLUNTARIO (
    ID_VOLUNTARIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(100) NOT NULL,
    TELEFONE VARCHAR2(20),
    ESPECIALIDADE VARCHAR2(100),
    DATA_CADASTRO DATE DEFAULT SYSDATE NOT NULL
)
/

CREATE TABLE TB_RELATORIO_COLETA (
    ID_RELATORIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_OPERACAO NUMBER NOT NULL,
    ID_VOLUNTARIO NUMBER NOT NULL,
    QUANTIDADE_RESIDUOS NUMBER NOT NULL,
    TIPO_RESIDUO VARCHAR2(100) NOT NULL,
    OBSERVACOES VARCHAR2(255),
    DATA_RELATORIO DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_RELATORIO_VOLUNTARIO FOREIGN KEY (ID_VOLUNTARIO)
        REFERENCES TB_VOLUNTARIO(ID_VOLUNTARIO)
)
/